import assert from 'node:assert/strict';
import fs from 'node:fs';
import { validateContribution } from '../lib/contribution-validation.ts';
import { workflows } from '../lib/workflows.ts';
const data=JSON.parse(fs.readFileSync('lib/content.json','utf8'));
const ids=data.prompts.map(p=>p.id);
assert.equal(ids.length,29);assert.equal(new Set(ids).size,29);
assert.equal(data.categories.length,7);
for(let i=1;i<=29;i++)assert.ok(ids.includes('P'+String(i).padStart(2,'0')));
for(const p of data.prompts){assert.ok(data.categories.some(c=>c.id===p.category));assert.ok(p.body.length>100);assert.ok(!p.body.includes('libfile_'));}
for(const w of workflows)for(const [id] of w.steps)assert.ok(ids.includes(id),w.id+': invalid prompt '+id);
for(const c of ['core','readonly','research'])assert.ok(data.contracts[c].length>300);
const v={kind:'new',title:'Test reusable prompt',category:'A',content:'Create a clear draft using the supplied context and state the assumptions.',reason:'This helps clarify the initial discovery process.'};
assert.equal(validateContribution(v,ids),null);
assert.ok(validateContribution({...v,reason:'why'},ids));
assert.ok(validateContribution({...v,category:'Z'},ids));
assert.ok(validateContribution({...v,kind:'edit',promptId:'P99'},ids));
assert.equal(validateContribution({...v,kind:'edit',promptId:'P04'},ids),null);
assert.ok(validateContribution({...v,content:'x'.repeat(30001)},ids));
assert.ok(validateContribution({...v,title:'x'.repeat(161)},ids));
assert.ok(validateContribution(null,ids));
console.log('PASS: 29 unique prompts, 7 categories, 4 linked workflows, 3 context contracts, and contribution validation boundaries.');
const { DatabaseSync } = await import('node:sqlite');
const db=new DatabaseSync(':memory:');
const migration=fs.readdirSync('drizzle').find(f=>f.endsWith('.sql'));
db.exec(fs.readFileSync('drizzle/'+migration,'utf8'));
const insert=db.prepare('INSERT INTO contributions (id,kind,prompt_id,title,category,content,reason,author_id,created_at) VALUES (?,?,?,?,?,?,?,?,?)');
insert.run('qa-new','new',null,v.title,v.category,v.content,v.reason,'test-user',Date.now());
insert.run('qa-edit','edit','P04',v.title,v.category,v.content,v.reason,'test-user',Date.now());
assert.equal(db.prepare('SELECT count(*) AS n FROM contributions').get().n,2);
assert.equal(db.prepare('SELECT status FROM contributions WHERE id=?').get('qa-edit').status,'pending');
assert.equal(db.prepare('SELECT prompt_id FROM contributions WHERE id=?').get('qa-edit').prompt_id,'P04');
assert.equal(JSON.parse(fs.readFileSync('lib/content.json')).prompts.length,29);
db.close();console.log('PASS: migration applies to SQLite; new and edit proposals persist as pending without altering the curated collection.');
