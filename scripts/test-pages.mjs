import assert from 'node:assert/strict';
import fs from 'node:fs';
import {createIssueDraft, pageLink} from '../pages/github.mjs';
import {validateContribution} from '../lib/contribution-validation.ts';
const sample = {kind:'edit',promptId:'P04',title:'Map a user journey',category:'B',content:'Map goals, decisions, and handoffs using the supplied evidence. Include alternative paths.',reason:'Clarify exception paths without inventing requirements.'};
assert.equal(validateContribution(sample,['P04']),null);
const draft=createIssueDraft(sample,'User experience and project mapping');
const url=new URL(draft.url);
assert.equal(url.origin,'https://github.com');
assert.equal(url.pathname,'/HectorFCruzPO/promptpath/issues/new');
assert.equal(url.searchParams.get('body'),draft.body);
assert.ok(draft.body.includes(sample.reason));
assert.ok(draft.body.includes(sample.content));
assert.ok(draft.title.startsWith('[Prompt edit P04]'));
const large=createIssueDraft({...sample,content:'🧭 & ? # /\n'.repeat(1800)},'UX');
assert.equal(large.prefilled,false);
assert.ok(large.body.includes('🧭 & ? # /\n'.repeat(1800).trim()));
assert.equal(new URL(large.url).searchParams.has('body'),false);
assert.ok(large.url.length<7000);
assert.ok(createIssueDraft({...sample,kind:'new'},'UX').title.startsWith('[Prompt proposal]'));
const link=new URL(pageLink('https://example.github.io/promptpath/?old=1#ignored',{prompt:'P04'}));
assert.equal(link.pathname,'/promptpath/');
assert.equal(link.search,'?prompt=P04');
assert.equal(link.hash,'');
const app=fs.readFileSync('pages/App.tsx','utf8');
assert.ok(!app.includes('/api/contributions'));
assert.ok(!app.includes('signin-with-chatgpt'));
const html=fs.readFileSync('pages-dist/index.html','utf8');
assert.ok(html.includes('./assets/'));
assert.ok(!html.includes('src="/assets/'));
const bundle=fs.readdirSync('pages-dist/assets').filter(x=>x.endsWith('.js')).map(x=>fs.readFileSync('pages-dist/assets/'+x,'utf8')).join('\n');
assert.ok(!bundle.includes('/api/contributions'));
for(const id of ['P01','P29'])assert.ok(bundle.includes(id));
assert.ok(bundle.includes('Read-only'));
console.log('PASS: issue drafts retain wording/reason, long Unicode drafts use copy/paste, shared links retain the repository path, and the production bundle has no hosted API dependency.');
